/* =====================================================================
   Имя сети-соперника — по городу партии (местный слой «кто есть кто»,
   src/data/story-cast.js): в Уфе «Хлебный двор», в Москве «Столичный хлеб»,
   в Казани «Тандыр». Значение — свойство-геттер, поэтому и движок
   (S.rival.name в newGame), и интерфейс (вкладка «Рынок», второй акт) видят
   одно и то же имя. Для Уфы возвращается ровно прежняя строка: её партии,
   тексты и прогоны ботов побайтно прежние. BK_CFG='{"RIVAL_NAME":"…"}'
   по-прежнему переопределяет константу (через set).
   ===================================================================== */
(function () {
  const DEF = BK.CFG.RIVAL_NAME;
  let forced = null;
  try {
    Object.defineProperty(BK.CFG, 'RIVAL_NAME', {
      configurable: true, enumerable: true,
      get() {
        if (forced != null) return forced;
        const C = BK.STORY_CAST;
        return (C && C.rivalNow) ? C.rivalNow() : DEF;
      },
      set(v) { forced = v; },
    });
  } catch (e) { /* старый браузер — остаётся прежняя строка */ }
  BK.CFG.RIVAL_NAME_DEFAULT = DEF;
})();
