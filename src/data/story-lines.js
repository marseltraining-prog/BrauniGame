  /* «Острота» проблем месяца (§6): кандидаты {sit, hero, w, n, sum}. Веса нормированы по
     практике ботов (good/avg): списания 0,5–2,4 % выручки, рейтинг сети 4,0–4,9, доля
     убыточных точек 0–12 %, доля уставших 0–20 %, потери от «Двора» 3–17 %. Поэтому
     «хроническое» (усталость, соперник, убыточная точка) весит ~0,8–1,2, а острое
     (кассовый разрыв, кризис, уходы, списания, рейтинг) — выше; хорошее (рост, праздник,
     качество, уважение, ровный голос Рашида) идёт запасным с мягкими весами. */
  function problemsOf(S) {
    const E = BK.Engine || {}, CFG = BK.CFG || {};
    const out = [];
    const h = (S && S.history) || [];
    const last = h.length ? h[h.length - 1] : null, prev = h.length > 1 ? h[h.length - 2] : null;
    if (!last) return out;
    const open = openStores(S), pnl = last.pnl || {};
    const day = numOf(S.day), rev = Math.max(1, numOf(last.rev));
    const cnt = (f) => { try { return numOf(f()); } catch (e) { return 0; } };   // старые сохранения и частичные состояния
    const staff = cnt(() => E.allStaff(S)) + cnt(() => E.bakersTotal(S));
    const add = (sit, w, n, sum) => { const hero = SITUATION_HERO[sit]; if (hero && w > 0) out.push({ sit, hero, w, n: n == null ? null : n, sum: sum == null || !isFinite(sum) ? null : Math.round(sum) }); };

    // кризис — самое громкое, что бывает (Эльвира)
    const ev = S.ev || {};
    const crisisDay = ev.lastCrisis && ev.last ? numOf(ev.last[ev.lastCrisis]) : 0;
    if (ev.pending && ev.pending.crisis) add('crisis', 1.7, null, null);
    else if (crisisDay && day - crisisDay < 60) add('crisis', 1.35, null, null);

    // долг: минус на счёте, второй месяц подряд, платежи при убытке (Эльвира)
    if (numOf(S.cash) < 0) add('debt', 1.55, null, Math.abs(numOf(S.cash)));
    else if (numOf(S.negMonths) > 0) add('debt', 1.2, null, Math.abs(numOf(S.cash)));
    else if (numOf(S.loan) > 0 && numOf(last.profit) < 0) add('debt', 0.95, null, loanPay(S));

    // месяц в минусе (Эльвира): заметный минус, а не случайные тысячи
    const lossK = numOf(last.profit) < 0 ? -numOf(last.profit) / rev : 0;
    if (lossK > 0.005) add('money', 1.3 + Math.min(0.4, lossK * 2), null, -numOf(last.profit));

    // люди: уходы, недовольные, вакансии, переработки (Гуля) — по доле от штата
    const unhappy = CFG.MOOD_UNHAPPY != null ? CFG.MOOD_UNHAPPY : 45;
    let sad = 0, tired = 0, vac = 0, losing = 0, worstStaff = null, worstW = 0;
    for (const st of open) {
      let s0 = 0, t0 = 0;
      for (const e of st.staff || []) { if (numOf(e.mood) < unhappy) s0++; if (numOf(e.fatigue) > 55) t0++; }
      const v = E.vacancies ? numOf(E.vacancies(st)) : 0;
      vac += v; sad += s0; tired += t0;
      if (st.last && numOf(st.last.profit) < 0) losing++;
      const w = s0 * 2 + t0 + v;
      if (w > worstW) { worstW = w; worstStaff = st; }
    }
    const nStaff = worstStaff ? worstStaff.num : null, staffK = Math.max(1, staff);
    const drop = prev ? numOf(prev.staff) - numOf(last.staff) : 0;
    if (drop / staffK > 0.02) add('quits', 1.15 + Math.min(0.6, drop / staffK * 12), nStaff, payrollOf(worstStaff));
    if (sad / staffK > 0.02) add('quits', 0.95 + Math.min(0.6, sad / staffK * 4), nStaff, payrollOf(worstStaff));
    else if (vac / staffK > 0.05) add('quits', 0.8 + Math.min(0.4, vac / staffK * 2), nStaff, payrollOf(worstStaff));
    if (tired / staffK > 0.1) add('overwork', 0.75 + Math.min(0.5, tired / staffK * 2), nStaff, payrollOf(worstStaff));

    // списания (Рашид): норма у ботов 0,5–1,2 % выручки, выше 1,4 % — уже разговор
    const wK = numOf(pnl.waste) / rev;
    if (wK > 0.014) { const st = worst(open, wasteK); add('waste', 1.0 + Math.min(0.6, (wK - 0.014) / 0.01), st ? st.num : null, numOf(pnl.waste)); }

    // рейтинг сети (Семён): у хорошего бота 4,7–4,9, у среднего 4,5; ниже 4,15 — середина
    const nr = E.networkRating ? E.networkRating(S) : null;
    if (nr != null && nr < 4.15) { const st = worst(open, (x) => 5 - (E.storeRating ? E.storeRating(S, x) : numOf(x.rating))); add('rating', 0.95 + Math.min(0.6, (4.15 - nr) * 1.2), st ? st.num : null, repairOf(S, st)); }

    // соперник (Олег): новая точка «Двора» рядом или потеря больше 15 % гостей
    const rv = (S && S.rival) || {}, rs = rv.enabled ? rv.stores || [] : [];
    const fresh = rs.filter((o) => day - numOf(o.day) < 45).length;
    const near = nearRival(S, open);
    if (near && fresh) add('rival', 0.95 + Math.min(0.5, fresh * 0.1 + near.loss), near.st.num, null);
    else if (near && near.loss >= 0.15) add('rival', 0.85 + Math.min(0.4, near.loss), near.st.num, null);

    // слабые продажи: доля убыточных точек сети, а не одна случайная точка (Гуля)
    const losingK = open.length ? losing / open.length : 0;
    if (losingK >= 0.06) { const st = worst(open, (x) => { const L = x.last; return L && numOf(L.rev) > 0 && numOf(L.profit) < 0 ? -numOf(L.profit) / numOf(L.rev) : 0; }); add('salelow', 1.0 + Math.min(0.6, losingK * 3), st ? st.num : null, st ? -numOf(st.last.profit) : null); }

    // хорошее — мягкие веса: рост, праздник, качество, уважение, ровный месяц
    if (prev && numOf(last.stores) > numOf(prev.stores)) { const st = newestOf(open); add('growth', 0.6, st ? st.num : null, capexOf(S, st)); }
    let hol = null; try { hol = E.upcomingHolidays ? E.upcomingHolidays(S, 1) : null; } catch (e) { hol = null; }
    if (hol && hol.length && hol[0].active) add('holiday', 0.55, null, null);
    if (nr != null && nr >= 4.3) { const st = bestOf(open, (x) => (E.storeRating ? E.storeRating(S, x) : numOf(x.rating))); add('quality', 0.45, st ? st.num : null, null); }
    if (open.length >= 15) add('respect', 0.4, null, null);
    add('mentor', 0.3, null, null);   // запасной ровный голос Рашида
    return out;
  }

  // Вариант подстановок: {n}/{sum} нужны тексту — берём только тот вариант, где цифра известна.
  function pickLine(hero, sit, tone, v, roll) {
    const set = LINES[hero] && LINES[hero][sit]; if (!set) return null;
    const arr = set[tone] || set.even || set.warm || set.cold; if (!arr || !arr.length) return null;
    const start = Math.abs(roll | 0) % arr.length;
    for (let k = 0; k < arr.length; k++) {
      const i = (start + k) % arr.length, raw = arr[i];
      if (!raw || !String(raw).trim()) continue;
      if (/\{n\}/.test(raw) && v.n == null) continue;
      if (/\{sum\}/.test(raw) && v.sum == null) continue;
      return { i, text: fill(raw, v) };
    }
    return null;
  }
  function monthRoll(S, sit) {   // детерминированный выбор варианта: сид + месяц + ситуация
    let h = (numOf(S.seed) | 0) ^ 0x9e3779b9;
    const s = String(sit) + ':' + Math.floor(numOf(S.day) / 30.44);
    for (let i = 0; i < s.length; i++) h = (Math.imul(h >>> 0, 31) + s.charCodeAt(i)) >>> 0;
    return h % 100000;
  }
  function lastScene(S) {
    const log = (S.story && S.story.log) || [];
    for (let i = log.length - 1; i >= 0; i--) if (log[i] && log[i].id && log[i].title) return log[i];
    return null;
  }
  function sceneHeroes(it) {
    for (const sc of BK.STORY.scenes || []) if (sc.id === it.id) return sc.who || [];
    return [];
  }

  // Реплика месяца: null — молчим (сюжет выключен/не начат, лимит месяца, нет текста или История уже сказала).
  function lineOfMonth(S) {
    if (!S || !S.story || !S.story.v) return null;                                   // сюжет не начат
    if (BK.CFG && BK.CFG.STORY && BK.CFG.STORY.ON === false) return null;            // сюжет выключен
    const E = BK.Engine || {}, R = S.story;
    if (R.mode === 'off') return null;
    const day = numOf(S.day), h = S.history || [], last = h.length ? h[h.length - 1] : null;
    if (!last) return null;                                                          // первого отчёта ещё нет
    let cur = String(Math.floor(day / 30.44)), when = '';
    if (E.dateOf) { const dt = E.dateOf(day); cur = dt.y + '-' + dt.m; }
    if (E.MONTHS) when = E.MONTHS[last.m] + ' ' + last.y;
    const prev = R.lineM;
    if (prev && prev.cur === cur && prev.text) return prev;                          // в этом месяце уже сказали — та же строка
    if (prev && day - numOf(R.lastLine) < LINE_GAP_DAYS) return null;                // не чаще раза в месяц
    const scene = lastScene(S);
    const list = problemsOf(S);
    const muted = (hero) => !!(scene && day - numOf(scene.day) <= SCENE_MUTE_DAYS && sceneHeroes(scene).indexOf(hero) >= 0);
    // ротация: кто говорил недавно — уступает; одно и то же (герой + ситуация) не повторяем подряд
    const hist = R.lineHist || (R.lineHist = []);
    const spoke = (c) => { let n = 0; for (let i = Math.max(0, hist.length - 24); i < hist.length; i++) if (hist[i] && hist[i].h === c.hero) n++; return n; };
    const lastItem = hist.length ? hist[hist.length - 1] : null;
    const weight = (c) => c.w * (prev && prev.hero === c.hero ? 0.7 : 1) * (lastItem && lastItem.h === c.hero && lastItem.s === c.sit ? 0.5 : 1) * Math.max(0.55, 1 - spoke(c) * 0.06);
    list.sort((a, b) => weight(b) - weight(a));
    for (const c of list) {
      if (muted(c.hero)) continue;                                                   // этого героя История уже показала
      const rel = numOf((R.rel || {})[c.hero]), tone = toneOf(rel);
      const v = { rel, n: c.n, sum: c.sum, name: (R.hero && R.hero.name) || 'шеф' };
      const pick = pickLine(c.hero, c.sit, tone, v, monthRoll(S, c.sit));
      if (!pick) continue;                                                           // нет текста на эту ситуацию — не выдумываем
      const item = { cur, day, hero: c.hero, sit: c.sit, tone, i: pick.i, n: c.n, sum: c.sum, when, text: pick.text };
      R.lineM = item; R.lastLine = day;
      hist.push({ d: day, h: c.hero, s: c.sit });
      while (hist.length > 36) hist.shift();
      return item;
    }
    return null;
  }
  // Строка для отчёта месяца (Сводка — под блоком «История»; Финансы — под отчётом).
  function lineHtml(S) {
    const L = lineOfMonth(S); if (!L || !L.text) return '';
    const hero = (BK.STORY.heroes || {})[L.hero] || {};
    const when = L.when ? String(L.when).split(' ')[0] : '';
    return '<div class="sec storyb st-line"><div class="st-last">'
      + '<span class="st-ld">Реплика' + (when ? ' · ' + htmlEsc(when) : '') + '</span>'
      + '<span class="st-lt"><b>' + htmlEsc(hero.name || L.hero) + '</b><small>«' + htmlEsc(L.text) + '»</small></span>'
      + '</div></div>';
  }
  // Проверка текстов: заполненность, подстановки, дубли. Возвращает список проблем ([] — всё хорошо).
  function linesCheck() {
    const probs = [];
    const want = ['gulya', 'oleg', 'semyon', 'elvira'];
    for (const h of want) if (!LINES[h]) probs.push(`нет героя «${h}»`);
    for (const sit of Object.keys(SITUATION_HERO)) {          // у каждой ситуации отчёта (§6) должен быть текст
      const hero = SITUATION_HERO[sit];
      if (!LINES[hero] || !LINES[hero][sit]) probs.push(`ситуация «${sit}»: нет текстов у героя «${hero}»`);
    }
    for (const h of Object.keys(LINES)) {
      for (const sit of Object.keys(LINES[h])) {
        const set = LINES[h][sit] || {};
        if (!set.warm || !set.warm.length) probs.push(`${h}.${sit}: нет тёплых реплик`);
        if (!set.cold || !set.cold.length) probs.push(`${h}.${sit}: нет холодных реплик`);
        const seen = {};
        for (const tone of Object.keys(set)) {
          for (const t of set[tone]) {
            if (typeof t !== 'string' || !t.trim()) probs.push(`${h}.${sit}.${tone}: пустая реплика`);
            const ph = String(t).match(/\{[a-z]+(?::[^}]*)?\}/g) || [];
            for (const p of ph) if (!/^\{(n|sum|name)\}$/.test(p)) probs.push(`${h}.${sit}.${tone}: неизвестная подстановка ${p}`);
            if (seen[t]) probs.push(`${h}.${sit}: дубль «${t.slice(0, 24)}…»`);
            seen[t] = 1;
            if (String(t).length > 140) probs.push(`${h}.${sit}: слишком длинная реплика (${String(t).length})`);
          }
        }
      }
    }
    return probs;
  }

  BK.STORY.lines = LINES;
