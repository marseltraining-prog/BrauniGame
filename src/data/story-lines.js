  // Тон по отношениям: docs/story.md §4.3 (≥10 тёплый, −20…10 ровный, ≤−20 холодный).
  function toneOf(rel) {
    const r = typeof rel === 'number' ? rel : 0;
    if (r >= 10) return 'warm';
    if (r > -20) return 'even';
    return 'cold';
  }
  function fmtSum(v) {
    if (v == null || v === '') return '…';
    if (typeof v === 'string') return v;
    if (BK.fmtMoney) { try { return BK.fmtMoney(v); } catch (e) { /* ниже */ } }
    try { return new Intl.NumberFormat('ru-RU').format(Math.round(v)) + ' ₽'; } catch (e) { return Math.round(v) + ' ₽'; }
  }
  function fill(text, v) {
    return String(text)
      .replace(/\{n\}/g, v.n != null ? String(v.n) : '№')
      .replace(/\{sum\}/g, fmtSum(v.sum))
      .replace(/\{name\}/g, v.name != null ? String(v.name) : 'шеф');
  }
  // Получение реплики. opts: { rel, tone, n, sum, name, rnd, pick }.
  // rnd — функция [0,1) для случайного выбора; без неё берётся первый вариант (детерминированно).
  function lineFor(hero, situation, opts) {
    const o = opts || {};
    const set = LINES[hero] && LINES[hero][situation];
    if (!set) return '';
    const tone = o.tone || (o.rel != null ? toneOf(o.rel) : 'even');
    const arr = set[tone] || set.even || set.warm || set.cold || [];
    if (!arr.length) return '';
    let i = 0;
    if (o.pick != null) i = Math.abs(o.pick | 0) % arr.length;
    else if (typeof o.rnd === 'function') i = Math.floor(o.rnd() * arr.length) % arr.length;
    return fill(arr[i], o);
  }
  function situations() {
    const out = {};
    for (const h of Object.keys(LINES)) out[h] = Object.keys(LINES[h]);
    return out;
  }
  // Проверка текстов: заполненность, подстановки, дубли. Возвращает список проблем ([] — всё хорошо).
  function linesCheck() {
    const probs = [];
    const KNOWN = /\{(n|sum|name)\}/g;
    const want = ['gulya', 'oleg', 'semyon', 'elvira'];
    for (const h of want) if (!LINES[h]) probs.push(`нет героя «${h}»`);
    for (const h of Object.keys(LINES)) {
      for (const sit of Object.keys(LINES[h])) {
        const set = LINES[h][sit] || {};
        if (!set.warm || !set.warm.length) probs.push(`${h}.${sit}: нет тёплых реплик`);
        if (!set.cold || !set.cold.length) probs.push(`${h}.${sit}: нет холодных реплик`);
        const seen = {};
        for (const tone of Object.keys(set)) {
          for (const t of set[tone]) {
            if (typeof t !== 'string' || !t.trim()) probs.push(`${h}.${sit}.${tone}: пустая реплика`);
            const ph = String(t).match(/\{[a-z]+(?::[^}]*)?\}/g) || [];
            for (const p of ph) if (!/^\{(n|sum|name)\}$/.test(p)) probs.push(`${h}.${sit}.${tone}: неизвестная подстановка ${p}`);
            if (seen[t]) probs.push(`${h}.${sit}: дубль «${t.slice(0, 24)}…»`);
            seen[t] = 1;
            if (String(t).length > 140) probs.push(`${h}.${sit}: слишком длинная реплика (${String(t).length})`);
          }
        }
      }
    }
    return probs;
  }

  BK.STORY.lines = LINES;
