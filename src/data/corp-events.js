/* ---------- Подстановка плейсхолдеров (чистая функция, без DOM) ----------
   ctx: { city, city2, director, director2, district, poacher, offerPct, price, n, amount, pct, rival, months }
   {g:муж|жен} — по полу ctx.director, {g2:…|…} — по ctx.director2 (BK.isFemale из world.js). */
BK.corpText = function (str, ctx) {
  ctx = ctx || {};
  var fem = function (name) { return typeof BK.isFemale === 'function' && BK.isFemale(name); };
  var plural = function (n, a) { n = Math.abs(n) % 100; var d = n % 10; return a[n > 10 && n < 20 ? 2 : d === 1 ? 0 : d >= 2 && d <= 4 ? 1 : 2]; };
  var nouns = { stores:['точка', 'точки', 'точек'], people:['человек', 'человека', 'человек'], weeks:['неделя', 'недели', 'недель'] };
  var forms = function (c) { return BK.CITY_FORMS[c] || { in:'в городе ' + c, from:'из города ' + c, to:'в город ' + c }; };
  var s = String(str || '').replace(/\{(g2?):([^|}]*)\|([^}]*)\}/g, function (_, k, m, f) {
    return fem(k === 'g2' ? ctx.director2 : ctx.director) ? f : m;
  });
  return s.replace(/\{(\w+)\}/g, function (all, k) {
    var cm = /^(in|from|to)City(2?)$/.exec(k);
    if (cm) { var c = cm[2] ? ctx.city2 : ctx.city; return c ? forms(c)[cm[1]] : all; }
    if (nouns[k] && ctx.n != null) return ctx.n + ' ' + plural(+ctx.n, nouns[k]);
    if (k === 'rival' && ctx.rival == null) return 'Хлебный двор';
    return ctx[k] != null ? String(ctx[k]) : all;
  });
};

