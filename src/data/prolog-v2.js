  /* ---------------- очередь дилемм ---------------- */
  function push(P, id) {
    if (!DILEMMAS[id]) return false;
    if (P.v2.seen[id]) return false;
    P.cards.push({ id, v: {}, v2: 1 });
    P.v2.seen[id] = P.m;
    return true;
  }
  // подмешать дилемму в начало очереди (хук в advance: сюжетная сцена ждёт, дилемма — нет)
  function overlay(P) {
    if (!P.v2) return false;
    if (P.v2.dil.length) {
      const id = P.v2.dil.shift();
      if (push(P, id)) return true;
      if (P.v2.dil.length) return overlay(P);
      return false;
    }
    return false;
  }
  // раз в N месяцев — одна случайная дилемма из ещё не виденных
  function maybeDil(P) {
    if (!P.v2) return;
    const R = P.v2.rhythm || V();
    if (P.m - (P.v2.lastDil || -9) < (R.gap || 2)) return;
    if (rnd(P) > (R.dilPer || 0.55)) return;
    const ids = Object.keys(DILEMMAS).filter((id) => !P.v2.seen[id]);
    if (!ids.length) return;
    P.v2.dil.push(ids[Math.floor(rnd(P) * ids.length)]);
  }

