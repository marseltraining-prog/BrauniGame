  // долг: сверх 30 тыс. минус в кошельке — давление на настроение и репутацию
  function debtPressure(P) {
    if (!P.v2) return { mood: 0, rep: 0, v: 0 };
    const v = Math.max(0, -P.cash - 30000);
    if (v <= 0) return { mood: 0, rep: 0, v: 0 };
    const k = V();
    return { mood: -Math.min(12, Math.round(v / 10000) * (k.DEBT_PRESSURE || 4)), rep: -Math.min(6, Math.round(v / 20000) * 2), v };
  }
  // «Смена»: усталость и болезнь бьют по точности и скорости
  function shiftMods(P) {
    if (!P.v2) return null;
    const k = V();
    let cloth = 0, pat = 0, speed = 1, why = '';
    if (P.hp < k.TIRED_SHIFT) { cloth = 0.12; pat = -1.5; speed = 0.9; why = 'Устали: очередь идёт быстрее, рука дрожит.'; }
    if (P.hp < 12) { cloth = 0.22; pat = -3; speed = 0.82; why = 'На исходе: гости чувствуют, что вы на пределе.'; }
    if (P.sickNow) { cloth += 0.15; pat -= 2; why = 'Вы на смене больным — гости это видят.'; }
    if (P.mood < 25) { pat -= 1; cloth += 0.06; }
    const d = debtPressure(P);
    if (d.mood) { pat -= 1; why = why || 'Мысли о долге не дают сосредоточиться.'; }
    const relV = (P.rel && (P.rel.rashid + P.rel.gulya)) || 0;
    if (relV <= -20) { pat -= 1.5; why = why || 'Смена смотрит на вас косо — и гости это чувствуют.'; }
    else if (relV >= 40) { pat += 1.5; }
    if (!why && P.sf && (P.sf.inspGood || P.sf.honest)) why = 'О вас хорошо говорят — работается легче.';
    return { cloth, pat, speed, why };
  }
  // предупреждение на кнопке «Выйти на смену»
