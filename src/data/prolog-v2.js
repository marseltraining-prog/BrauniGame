  // V() готовит CFG.PROLOGUE_V2 и запоминает цену болезни (доля оклада) в момент вызова
  function fitMoney(P) { if (P && P.v2 && !P.v2.sickMoney) P.v2.sickMoney = r100((BK.CFG.PROLOGUE.JOBS[P.job].pay || 42000) * V().SICK_MONEY_K); }
  const _init = init;
  BK.PrologV2.init = function (S) { const r = _init(S); const P = S && S.prologue; if (P && P.v2 && !P.v2.sickMoney) fitMoney(P); return r; };
  BK.PrologV2.tick = function (P) { fitMoney(P); return tick(P); };
  bridge();
