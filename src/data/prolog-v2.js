  function dueThreads(P) {
    if (!P.v2) return;
    for (const t of P.v2.threads.slice()) {
      if (t.due > P.m) continue;
      if (P.v2.fired[t.id + ':' + P.v2.threads.indexOf(t)]) { P.v2.threads.splice(P.v2.threads.indexOf(t), 1); continue; }
      threadFx(P, t);
      P.v2.fired[t.id + ':' + P.v2.threads.indexOf(t)] = 1;
      P.v2.fires.push({ who: t.who, dir: t.dir, m: P.m, note: t.note || t.gist });
      P.v2.threads.splice(P.v2.threads.indexOf(t), 1);
    }
  }
